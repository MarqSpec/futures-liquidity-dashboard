using System.Globalization;
using MarqSpec.FuturesLiquidityDashboard.Core.Instruments;
using MarqSpec.FuturesLiquidityDashboard.Core.Market;

namespace MarqSpec.FuturesLiquidityDashboard.Ingestion.Synthetic;

/// <summary>
/// A deterministic, self-consistent market for one contract (ARCHITECTURE.md D-12). A latent fair price follows a
/// random walk whose volatility and trade rate change with an activity regime and the time of day; aggressive
/// orders consume resting levels and move the best prices; resting size grows with depth and at round numbers.
/// On top of that it stages the order-flow situations the detectors look for (ARCHITECTURE.md D-25), so each can be
/// seen in the demo: walls that are pulled as price approaches (spoofs) or absorbed, iceberg orders that refill
/// after every fill, one-sided aggressive bursts (stacked imbalances, delta spikes) of which some fail and reverse
/// (trapped traders, delta exhaustion), and stop runs through the recent high or low that snap back (sweeps).
/// Every event is a normalized <see cref="MarketEvent"/>, so the engine cannot tell it from a real feed except by
/// the SIMULATED provenance. Not thread-safe: the feed steps it on one loop.
/// </summary>
public sealed class SyntheticInstrumentSimulator
{
    private readonly InstrumentSpec _spec;
    private readonly SyntheticProfile _profile;
    private readonly Random _random;

    // The trend/range phases draw from their own generator, so adding them left the rest of the market's draws as
    // they were.
    private readonly Random _phases;
    private readonly int _levels;
    private readonly Func<long, double> _timeOfDay;
    private readonly int _outageIntervalMs;
    private readonly int _outageDurationMs;
    private readonly SortedDictionary<long, long> _bids = [];
    private readonly SortedDictionary<long, long> _asks = [];
    private readonly List<Wall> _walls = [];
    private readonly Dictionary<(bool Bid, long Price), Iceberg> _icebergs = [];
    private readonly List<(long MinuteMs, long High, long Low)> _minuteRanges = [];
    private readonly List<MarketEvent> _out = [];

    private double _fair;
    private double _activity = 1.0;
    private long _lastMs;
    private long _epoch;
    private long _sequence;
    private long _tradeNumber;
    private long _nextOutageMs = long.MaxValue;
    private long _outageEndsMs = long.MinValue;
    private bool _connected;
    private Burst? _burst;
    private long _nextBurstMs;
    private long _nextStopRunMs;
    private bool _trending;
    private long _phaseEndsMs = long.MinValue;
    private double _trendSpeed;
    private double _anchor;

    public SyntheticInstrumentSimulator(
        InstrumentSpec spec,
        SyntheticProfile profile,
        int seed,
        int levelsPerSide,
        double startFairTicks,
        Func<long, double>? timeOfDay = null,
        int outageIntervalMs = 0,
        int outageDurationMs = 5_000)
    {
        _spec = spec ?? throw new ArgumentNullException(nameof(spec));
        _profile = profile ?? throw new ArgumentNullException(nameof(profile));
        ArgumentOutOfRangeException.ThrowIfLessThan(levelsPerSide, 4);
        _random = new Random(seed);
        _phases = new Random(unchecked(seed ^ 0x5EED_7EAD));
        _levels = levelsPerSide;
        _fair = startFairTicks;
        _timeOfDay = timeOfDay ?? (_ => 1.0);
        _outageIntervalMs = outageIntervalMs;
        _outageDurationMs = outageDurationMs;
    }

    public long BestBid => _bids.Count > 0 ? _bids.Keys.Last() : long.MinValue;

    public long BestAsk => _asks.Count > 0 ? _asks.Keys.First() : long.MaxValue;

    public bool Connected => _connected;

    /// <summary>Resting icebergs with hidden size left, for tests.</summary>
    public int ActiveIcebergs => _icebergs.Count;

    /// <summary>Builds the initial book and returns the connect status and the baseline snapshot.</summary>
    public IReadOnlyList<MarketEvent> Start(long nowMs)
    {
        _out.Clear();
        _lastMs = nowMs;
        var bestBid = (long)Math.Floor(_fair);
        for (var i = 0; i < _levels; i++)
        {
            _bids[bestBid - i] = BaseSize(bestBid - i, i);
            _asks[bestBid + 1 + i] = BaseSize(bestBid + 1 + i, i);
        }

        if (_outageIntervalMs > 0)
        {
            _nextOutageMs = nowMs + _outageIntervalMs;
        }

        _nextBurstMs = nowMs + _random.Next(20_000, 60_000);
        _nextStopRunMs = nowMs + _random.Next(120_000, 240_000);
        Connect(nowMs);
        return [.. _out];
    }

    /// <summary>
    /// Re-sends the connect status and a fresh snapshot without changing the market: used when history was
    /// generated by stepping this simulator and live streaming starts from where it stopped.
    /// </summary>
    public IReadOnlyList<MarketEvent> Resync(long nowMs)
    {
        _out.Clear();
        _lastMs = Math.Max(_lastMs, nowMs);
        Connect(nowMs);
        return [.. _out];
    }

    /// <summary>
    /// Advances the market to <paramref name="nowMs"/> and returns the events an upstream would have sent. While an
    /// outage lasts the market keeps moving but nothing is delivered; the step that starts an outage delivers only
    /// the disconnect, and the step that ends it delivers the reconnect and a new snapshot.
    /// </summary>
    public IReadOnlyList<MarketEvent> Step(long nowMs)
    {
        _out.Clear();
        var dtMs = Math.Clamp(nowMs - _lastMs, 0, 2_000);
        _lastMs = Math.Max(_lastMs, nowMs);
        if (dtMs == 0)
        {
            return [];
        }

        var dt = dtMs / 1000.0;
        UpdateRegime(dt);
        var tod = _timeOfDay(nowMs);
        PlanScenarios(nowMs);
        var drift = (_burst is { } b && nowMs < b.EndMs ? b.FairSpeed * dt : 0) + PhaseDrift(nowMs, dt);
        _fair += drift + (_random.NextGaussian() * _profile.VolatilityTicks * Math.Sqrt(dt) * _activity * Math.Sqrt(tod));

        Trade(nowMs, dt, tod);
        FollowFair(nowMs);
        Churn(nowMs, dt);
        ManageWalls(nowMs, dt);
        ManageIcebergs(nowMs, dt);
        Normalize(nowMs);

        if (_connected && nowMs >= _nextOutageMs)
        {
            _out.Clear();
            _connected = false;
            _outageEndsMs = nowMs + _outageDurationMs;
            _nextOutageMs = nowMs + _outageIntervalMs;
            Emit(Status(nowMs, connected: false));
            return [.. _out];
        }

        if (!_connected)
        {
            if (nowMs < _outageEndsMs)
            {
                return [];
            }

            _out.Clear();
            Connect(nowMs);
        }

        return [.. _out];
    }

    private void Connect(long nowMs)
    {
        _epoch++;
        _connected = true;
        Emit(Status(nowMs, connected: true));
        Emit(new DepthSnapshotEvent
        {
            Root = _spec.Root,
            ContractId = _spec.ContractId,
            SourceTimeMs = nowMs,
            ReceivedTimeMs = nowMs,
            Epoch = _epoch,
            Sequence = ++_sequence,
            Bids = _bids.Reverse().Select(l => new BookLevel(l.Key, l.Value)).ToList(),
            Asks = _asks.Select(l => new BookLevel(l.Key, l.Value)).ToList(),
            LevelsPerSide = _levels,
        });
    }

    /// <summary>The connection status now, with depth on or off: sent when the feed switches this product's depth (REQUIREMENTS.md FR-54).</summary>
    public FeedStatusEvent CurrentStatus(long nowMs, bool depthSubscribed) => Status(nowMs, _connected) with { DepthSubscribed = depthSubscribed };

    /// <summary>The best bid and offer now, as the quote stream sends them for a product without depth (REQUIREMENTS.md FR-54).</summary>
    public QuoteEvent Quote(long nowMs) => new()
    {
        Root = _spec.Root,
        ContractId = _spec.ContractId,
        SourceTimeMs = nowMs,
        ReceivedTimeMs = nowMs,
        Epoch = _epoch,
        Sequence = ++_sequence,
        BidTicks = _bids.Count > 0 ? BestBid : null,
        AskTicks = _asks.Count > 0 ? BestAsk : null,
    };

    private FeedStatusEvent Status(long nowMs, bool connected) => new()
    {
        Root = _spec.Root,
        ContractId = _spec.ContractId,
        SourceTimeMs = nowMs,
        ReceivedTimeMs = nowMs,
        Epoch = _epoch,
        Sequence = ++_sequence,
        Connected = connected,
        Provenance = FeedProvenance.Simulated,
    };

    private void UpdateRegime(double dt)
    {
        // A slow Markov switch between calm, normal and active markets, about every three minutes on average.
        if (_random.NextDouble() < dt / 180.0)
        {
            var draw = _random.NextDouble();
            _activity = draw < 0.25 ? 0.6 : draw < 0.8 ? 1.0 : 2.2;
        }
    }

    /// <summary>Whether the current phase is a trend (for tests): the market alternates trends and ranges (REQUIREMENTS.md FR-56).</summary>
    public bool Trending => _trending;

    /// <summary>
    /// The slow regime the trend-versus-range classifier reads (REQUIREMENTS.md FR-56): phases of two to five hours, either a
    /// steady drift of about a twentieth of the volatility per second, up or down, or a pull back to the level the
    /// range started at, with a half-life of about ten minutes. Roughly half the time is spent in each.
    /// </summary>
    private double PhaseDrift(long nowMs, double dt)
    {
        if (nowMs >= _phaseEndsMs)
        {
            var first = _phaseEndsMs == long.MinValue;
            _trending = first ? _phases.NextDouble() < 0.5 : !_trending;
            _phaseEndsMs = nowMs + (long)TimeSpan.FromMinutes(_phases.Next(120, 300)).TotalMilliseconds;
            _anchor = _fair;
            _trendSpeed = (_phases.NextDouble() < 0.5 ? -1 : 1) * _profile.VolatilityTicks * (0.04 + (0.04 * _phases.NextDouble()));
        }

        return _trending ? _trendSpeed * dt : -(_fair - _anchor) * (Math.Log(2) / 600.0) * dt;
    }

    private void PlanScenarios(long nowMs)
    {
        if (_burst is { } burst)
        {
            if (nowMs < burst.EndMs)
            {
                return;
            }

            _burst = null;
            if (burst.Fails && !burst.IsReversal)
            {
                // The push failed: price snaps back past where it started, against the burst's aggressors.
                var target = burst.StartFair - (burst.Direction * (1 + (_random.NextDouble() * 4)));
                var durationMs = _random.Next(5_000, 12_000);
                _burst = new Burst(-burst.Direction, nowMs + durationMs, (target - _fair) / (durationMs / 1000.0), _fair, Fails: false, IsReversal: true);
            }

            return;
        }

        if (nowMs >= _nextStopRunMs && _minuteRanges.Count >= 10)
        {
            // A stop run: drive just through the recent high or low, then fail back inside.
            _nextStopRunMs = nowMs + _random.Next(180_000, 420_000);
            var high = _minuteRanges.Max(r => r.High);
            var low = _minuteRanges.Min(r => r.Low);
            var up = high - _fair < _fair - low;
            var target = up ? high + 2 + _random.Next(0, 3) : low - 2 - _random.Next(0, 3);
            var durationMs = _random.Next(6_000, 15_000);
            _burst = new Burst(up ? 1 : -1, nowMs + durationMs, (target - _fair) / (durationMs / 1000.0), _fair, Fails: true, IsReversal: false);
            return;
        }

        if (nowMs >= _nextBurstMs)
        {
            // A one-sided aggressive burst; about two in five fail and reverse.
            _nextBurstMs = nowMs + _random.Next(45_000, 150_000);
            var direction = _random.NextDouble() < 0.5 ? 1 : -1;
            var durationMs = _random.Next(4_000, 12_000);
            var distance = 5 + (_random.NextDouble() * 9);
            _burst = new Burst(direction, nowMs + durationMs, direction * distance / (durationMs / 1000.0), _fair, Fails: _random.NextDouble() < 0.4, IsReversal: false);
        }
    }

    private void Trade(long nowMs, double dt, double tod)
    {
        var bursting = _burst is { } b && nowMs < b.EndMs;
        var rate = _profile.TradesPerSecond * _activity * tod * (bursting ? 3.0 : 1.0);
        var count = _random.NextPoisson(rate * dt);
        for (var i = 0; i < count; i++)
        {
            bool buy;
            if (bursting)
            {
                buy = _random.NextDouble() < (_burst!.Direction > 0 ? 0.92 : 0.08);
            }
            else
            {
                var mid = (BestBid + BestAsk) / 2.0;
                var pressure = Math.Tanh((_fair - mid) / 1.5);
                buy = _random.NextDouble() < 0.5 + (0.38 * pressure);
            }

            var size = _random.NextGeometric(_profile.MeanTradeSize * (0.7 + (0.3 * _activity)) * (bursting ? 1.6 : 1.0));
            Execute(nowMs, buy, size);
        }
    }

    private void Execute(long nowMs, bool buy, long size)
    {
        var book = buy ? _asks : _bids;
        var side = buy ? BookSide.Ask : BookSide.Bid;
        var swept = 0;
        while (size > 0 && book.Count > 0 && swept++ < 6)
        {
            var price = buy ? BestAsk : BestBid;
            var resting = book[price];
            var fill = Math.Min(size, resting);
            EmitTrade(nowMs, price, fill, buy);
            size -= fill;
            var left = resting - fill;
            SetLevel(nowMs, side, price, left);
            if (_icebergs.TryGetValue((!buy, price), out var iceberg))
            {
                // The exchange tops the displayed slice back up from the hidden reserve straight after the fill.
                var refill = Math.Min(iceberg.Clip - left, iceberg.Reserve);
                if (refill > 0)
                {
                    iceberg.Reserve -= refill;
                    left += refill;
                    SetLevel(nowMs, side, price, left);
                }

                if (iceberg.Reserve <= 0)
                {
                    _icebergs.Remove((!buy, price));
                }
            }

            if (left == 0)
            {
                // The level is gone: the opposite side often steps in to keep a one-tick market.
                if (buy && BestAsk - BestBid > 1 && _random.NextDouble() < 0.75)
                {
                    SetLevel(nowMs, BookSide.Bid, BestBid + 1, (BaseSize(BestBid + 1, 0) / 2) + 1);
                }
                else if (!buy && BestAsk - BestBid > 1 && _random.NextDouble() < 0.75)
                {
                    SetLevel(nowMs, BookSide.Ask, BestAsk - 1, (BaseSize(BestAsk - 1, 0) / 2) + 1);
                }

                Normalize(nowMs);
            }
        }
    }

    private void FollowFair(long nowMs)
    {
        // Quotes lean toward the latent fair price: the side in the way thins out and is pulled, unless an iceberg
        // is defending it, in which case aggressors have to trade through it.
        if (_fair > BestAsk + 0.6 && !_icebergs.ContainsKey((false, BestAsk)))
        {
            SetLevel(nowMs, BookSide.Ask, BestAsk, 0);
            if (BestAsk - BestBid > 1)
            {
                SetLevel(nowMs, BookSide.Bid, BestBid + 1, (BaseSize(BestBid + 1, 0) / 2) + 1);
            }
        }
        else if (_fair < BestBid - 0.6 && !_icebergs.ContainsKey((true, BestBid)))
        {
            SetLevel(nowMs, BookSide.Bid, BestBid, 0);
            if (BestAsk - BestBid > 1)
            {
                SetLevel(nowMs, BookSide.Ask, BestAsk - 1, (BaseSize(BestAsk - 1, 0) / 2) + 1);
            }
        }
    }

    private void Churn(long nowMs, double dt)
    {
        var updates = _random.NextPoisson(18 * _activity * dt);
        for (var i = 0; i < updates; i++)
        {
            var bid = _random.NextDouble() < 0.5;
            var depth = Math.Min(_levels - 1, (int)Math.Floor(-Math.Log(1 - _random.NextDouble()) * 4));
            var price = bid ? BestBid - depth : BestAsk + depth;
            var book = bid ? _bids : _asks;
            if (!book.TryGetValue(price, out var quantity) || _icebergs.ContainsKey((bid, price)))
            {
                continue;
            }

            var scale = BaseSize(price, depth);
            var change = (long)Math.Round(_random.NextGaussian() * 0.3 * scale);
            SetLevel(nowMs, bid ? BookSide.Bid : BookSide.Ask, price, Math.Max(1, quantity + change));
        }
    }

    private void ManageWalls(long nowMs, double dt)
    {
        if (_walls.Count < 3 && _random.NextDouble() < dt / 20.0)
        {
            var bid = _random.NextDouble() < 0.5;
            var distance = _random.Next(3, Math.Min(13, _levels - 1));
            var price = bid ? BestBid - distance : BestAsk + distance;
            var book = bid ? _bids : _asks;
            if (book.TryGetValue(price, out var quantity) && _walls.TrueForAll(w => w.Price != price) && !_icebergs.ContainsKey((bid, price)))
            {
                var extra = (long)(BaseSize(price, distance) * (3.5 + (_random.NextDouble() * 4.5)));
                _walls.Add(new Wall(bid, price, extra, nowMs + _random.Next(30_000, 240_000), _random.NextDouble() < 0.55));
                SetLevel(nowMs, bid ? BookSide.Bid : BookSide.Ask, price, quantity + extra);
            }
        }

        foreach (var wall in _walls.ToList())
        {
            var book = wall.Bid ? _bids : _asks;
            var side = wall.Bid ? BookSide.Bid : BookSide.Ask;
            if (!book.TryGetValue(wall.Price, out var quantity))
            {
                _walls.Remove(wall);
                continue;
            }

            var distance = wall.Bid ? BestBid - wall.Price : wall.Price - BestAsk;
            if (nowMs >= wall.ExpiresMs || (wall.PullsOnApproach && distance <= 1))
            {
                SetLevel(nowMs, side, wall.Price, Math.Max(1, quantity - Math.Min(wall.Extra, quantity)));
                _walls.Remove(wall);
            }
        }
    }

    private void ManageIcebergs(long nowMs, double dt)
    {
        if (_icebergs.Count >= 2 || _random.NextDouble() >= dt / 40.0)
        {
            return;
        }

        // A hidden order joins at or just behind the best price on one side; the fair price is nudged toward it so
        // aggressors actually lean on it.
        var bid = _random.NextDouble() < 0.5;
        var depth = _random.Next(0, 3);
        var price = bid ? BestBid - depth : BestAsk + depth;
        if (_icebergs.ContainsKey((bid, price)) || _walls.Exists(w => w.Price == price))
        {
            return;
        }

        var clip = Math.Max(2, (long)Math.Round(_profile.TopOfBookSize * (0.35 + (_random.NextDouble() * 0.35))));
        var reserve = clip * _random.Next(6, 17);
        _icebergs[(bid, price)] = new Iceberg(clip, reserve);
        var book = bid ? _bids : _asks;
        book.TryGetValue(price, out var quantity);
        SetLevel(nowMs, bid ? BookSide.Bid : BookSide.Ask, price, Math.Max(quantity, clip));
        _fair += bid ? -1.2 : 1.2;
    }

    private void Normalize(long nowMs)
    {
        // Keep exactly the top N contiguous ticks on each side, as a depth feed of N levels would deliver.
        if (_bids.Count == 0)
        {
            SetLevel(nowMs, BookSide.Bid, BestAsk - 1, BaseSize(BestAsk - 1, 0));
        }

        if (_asks.Count == 0)
        {
            SetLevel(nowMs, BookSide.Ask, BestBid + 1, BaseSize(BestBid + 1, 0));
        }

        // Liquid futures trade one tick wide almost all the time: when pulled or swept levels leave a gap wider than
        // two ticks, the side farther from the fair price steps in, so the spread cannot drift open over hours.
        while (BestAsk - BestBid > 2)
        {
            if (_fair - BestBid > BestAsk - _fair)
            {
                SetLevel(nowMs, BookSide.Bid, BestBid + 1, (BaseSize(BestBid + 1, 0) / 2) + 1);
            }
            else
            {
                SetLevel(nowMs, BookSide.Ask, BestAsk - 1, (BaseSize(BestAsk - 1, 0) / 2) + 1);
            }
        }

        var bestBid = BestBid;
        var bestAsk = BestAsk;
        for (var i = 0; i < _levels; i++)
        {
            if (!_bids.ContainsKey(bestBid - i))
            {
                SetLevel(nowMs, BookSide.Bid, bestBid - i, BaseSize(bestBid - i, i));
            }

            if (!_asks.ContainsKey(bestAsk + i))
            {
                SetLevel(nowMs, BookSide.Ask, bestAsk + i, BaseSize(bestAsk + i, i));
            }
        }

        foreach (var price in _bids.Keys.Where(p => p <= bestBid - _levels).ToList())
        {
            SetLevel(nowMs, BookSide.Bid, price, 0);
        }

        foreach (var price in _asks.Keys.Where(p => p >= bestAsk + _levels).ToList())
        {
            SetLevel(nowMs, BookSide.Ask, price, 0);
        }

        foreach (var key in _icebergs.Keys.Where(k => !(k.Bid ? _bids : _asks).ContainsKey(k.Price)).ToList())
        {
            _icebergs.Remove(key);
        }
    }

    private void SetLevel(long nowMs, BookSide side, long price, long quantity)
    {
        var book = side == BookSide.Bid ? _bids : _asks;
        book.TryGetValue(price, out var previous);
        if (previous == quantity || (quantity <= 0 && previous == 0))
        {
            return;
        }

        if (quantity <= 0)
        {
            book.Remove(price);
        }
        else
        {
            book[price] = quantity;
        }

        Emit(new DepthUpdateEvent
        {
            Root = _spec.Root,
            ContractId = _spec.ContractId,
            SourceTimeMs = nowMs,
            ReceivedTimeMs = nowMs,
            Epoch = _epoch,
            Sequence = ++_sequence,
            Side = side,
            PriceTicks = price,
            Quantity = Math.Max(0, quantity),
        });
    }

    private void EmitTrade(long nowMs, long price, long quantity, bool buy)
    {
        _tradeNumber++;
        var minute = nowMs - (nowMs % 60_000);
        if (_minuteRanges.Count == 0 || _minuteRanges[^1].MinuteMs != minute)
        {
            _minuteRanges.Add((minute, price, price));
            if (_minuteRanges.Count > 30)
            {
                _minuteRanges.RemoveAt(0);
            }
        }
        else
        {
            var last = _minuteRanges[^1];
            _minuteRanges[^1] = (minute, Math.Max(last.High, price), Math.Min(last.Low, price));
        }

        Emit(new TradeEvent
        {
            Root = _spec.Root,
            ContractId = _spec.ContractId,
            SourceTimeMs = nowMs,
            ReceivedTimeMs = nowMs,
            Epoch = _epoch,
            Sequence = ++_sequence,
            PriceTicks = price,
            Quantity = quantity,
            Aggressor = buy ? BookSide.Bid : BookSide.Ask,
            TradeId = string.Create(CultureInfo.InvariantCulture, $"{_spec.Root}-S-{_tradeNumber}"),
        });
    }

    private void Emit(MarketEvent marketEvent) => _out.Add(marketEvent);

    private long BaseSize(long price, int depth)
    {
        var round = price % _profile.RoundNumberTicks == 0 ? 2.2 : price % (_profile.RoundNumberTicks / 2) == 0 ? 1.4 : 1.0;
        var noise = Math.Exp(_random.NextGaussian() * 0.3);
        return Math.Max(1, (long)Math.Round(_profile.TopOfBookSize * (1 + (_profile.DepthGrowth * depth)) * round * noise));
    }

    private sealed record Wall(bool Bid, long Price, long Extra, long ExpiresMs, bool PullsOnApproach);

    private sealed class Iceberg(long clip, long reserve)
    {
        public long Clip { get; } = clip;

        public long Reserve { get; set; } = reserve;
    }

    /// <param name="FairSpeed">Ticks per second the fair price drifts while the burst lasts.</param>
    private sealed record Burst(int Direction, long EndMs, double FairSpeed, double StartFair, bool Fails, bool IsReversal);
}
